window.rng = SF.u.rng; /* canvas tools use this helper by name so their exported code is self-contained */
(function () {
  const COMMON = `
float h(vec2 p){p=fract(p*vec2(123.34,456.21));p+=dot(p,p+45.32);return fract(p.x*p.y);}
float n(vec2 p){vec2 i=floor(p),f=fract(p);f=f*f*(3.-2.*f);return mix(mix(h(i),h(i+vec2(1,0)),f.x),mix(h(i+vec2(0,1)),h(i+vec2(1,1)),f.x),f.y);}
float fbm(vec2 p){float a=.5,s=0.;for(int i=0;i<5;i++){s+=a*n(p);p=p*2.02+vec2(1.7,9.2);a*=.5;}return s;}
mat2 rot(float a){float c=cos(a),s=sin(a);return mat2(c,-s,s,c);}
`;
  function hex3(h) { const [r, g, b] = SF.u.h2r(h); return [r / 255, g / 255, b / 255]; }
  function source(spec) {
    const decl = Object.keys(spec.u).map(k => Array.isArray(spec.u[k]) ? `uniform vec3 ${k};` : `uniform float ${k};`).join('\n');
    return `precision highp float;\nuniform vec2 u_res;\nuniform float u_t;\n${decl}\n${COMMON}\nvoid main(){\n  vec2 uv=(gl_FragCoord.xy*2.-u_res)/min(u_res.x,u_res.y);\n  vec3 col=vec3(0.);\n${spec.body}\n  gl_FragColor=vec4(col,1.);\n}`;
  }
  function compile(gl, type, src) { const s = gl.createShader(type); gl.shaderSource(s, src); gl.compileShader(s); if (!gl.getShaderParameter(s, gl.COMPILE_STATUS)) throw new Error(gl.getShaderInfoLog(s)); return s; }
  function setup(canvas, spec) {
    const gl = canvas.getContext('webgl', { preserveDrawingBuffer: true, antialias: false }) || canvas.getContext('experimental-webgl', { preserveDrawingBuffer: true });
    if (!gl) throw new Error('WebGL is not available on this device');
    const pr = gl.createProgram();
    gl.attachShader(pr, compile(gl, gl.VERTEX_SHADER, 'attribute vec2 a;void main(){gl_Position=vec4(a,0.,1.);}'));
    gl.attachShader(pr, compile(gl, gl.FRAGMENT_SHADER, source(spec)));
    gl.linkProgram(pr); if (!gl.getProgramParameter(pr, gl.LINK_STATUS)) throw new Error(gl.getProgramInfoLog(pr));
    gl.useProgram(pr);
    const b = gl.createBuffer(); gl.bindBuffer(gl.ARRAY_BUFFER, b); gl.bufferData(gl.ARRAY_BUFFER, new Float32Array([-1, -1, 1, -1, -1, 1, 1, 1]), gl.STATIC_DRAW);
    const loc = gl.getAttribLocation(pr, 'a'); gl.enableVertexAttribArray(loc); gl.vertexAttribPointer(loc, 2, gl.FLOAT, false, 0, 0);
    return { gl, pr };
  }
  function frame(S, canvas, spec, t) {
    const { gl, pr } = S; gl.viewport(0, 0, canvas.width, canvas.height);
    gl.uniform2f(gl.getUniformLocation(pr, 'u_res'), canvas.width, canvas.height);
    gl.uniform1f(gl.getUniformLocation(pr, 'u_t'), t);
    for (const k in spec.u) { const v = spec.u[k], l = gl.getUniformLocation(pr, k); if (Array.isArray(v)) gl.uniform3f(l, v[0], v[1], v[2]); else gl.uniform1f(l, v); }
    gl.drawArrays(gl.TRIANGLE_STRIP, 0, 4);
  }
  /* live preview: returns {stop} */
  function run(canvas, spec, anim) {
    const S = setup(canvas, spec); let raf = 0, stopped = false; const t0 = performance.now();
    const loop = () => { if (stopped) return; frame(S, canvas, spec, (performance.now() - t0) / 1000); if (anim) raf = requestAnimationFrame(loop); };
    loop();
    return { stop() { stopped = true; cancelAnimationFrame(raf); const e = S.gl.getExtension('WEBGL_lose_context'); if (e) e.loseContext(); } };
  }
  /* one still frame as a data URL (thumbnails) using a shared canvas */
  let shared;
  function still(spec, w, h, t) {
    try {
      if (!shared) { shared = document.createElement('canvas'); }
      shared.width = w; shared.height = h;
      const S = setup(shared, spec); frame(S, shared, spec, t || 2.0);
      const url = shared.toDataURL('image/png');
      const e = S.gl.getExtension('WEBGL_lose_context'); if (e) e.loseContext();
      shared = null; /* a lost context cannot be reused */
      return url;
    } catch (e) { shared = null; return ''; }
  }
  /* standalone code a user can paste into their own page */
  function standalone(spec) {
    const frag = source(spec);
    const uni = JSON.stringify(spec.u);
    return `<canvas id="c" width="800" height="600" style="width:100%"></canvas>\n<script>\n/* Shader generated by StyleForge */\nconst FRAG = ${JSON.stringify(frag)};\nconst U = ${uni};\nconst c = document.getElementById('c'), gl = c.getContext('webgl');\nfunction sh(t, s){ const o = gl.createShader(t); gl.shaderSource(o, s); gl.compileShader(o); return o; }\nconst pr = gl.createProgram();\ngl.attachShader(pr, sh(gl.VERTEX_SHADER, 'attribute vec2 a;void main(){gl_Position=vec4(a,0.,1.);}'));\ngl.attachShader(pr, sh(gl.FRAGMENT_SHADER, FRAG)); gl.linkProgram(pr); gl.useProgram(pr);\nconst b = gl.createBuffer(); gl.bindBuffer(gl.ARRAY_BUFFER, b);\ngl.bufferData(gl.ARRAY_BUFFER, new Float32Array([-1,-1,1,-1,-1,1,1,1]), gl.STATIC_DRAW);\nconst l = gl.getAttribLocation(pr, 'a'); gl.enableVertexAttribArray(l); gl.vertexAttribPointer(l, 2, gl.FLOAT, false, 0, 0);\nfunction draw(t){\n  gl.viewport(0, 0, c.width, c.height);\n  gl.uniform2f(gl.getUniformLocation(pr, 'u_res'), c.width, c.height);\n  gl.uniform1f(gl.getUniformLocation(pr, 'u_t'), t / 1000);\n  for (const k in U) { const v = U[k], p = gl.getUniformLocation(pr, k); Array.isArray(v) ? gl.uniform3f(p, v[0], v[1], v[2]) : gl.uniform1f(p, v); }\n  gl.drawArrays(gl.TRIANGLE_STRIP, 0, 4); requestAnimationFrame(draw);\n}\nrequestAnimationFrame(draw);\n<\/script>`;
  }
  SF.gl = { run, still, standalone, hex3, source };
  /* shader tool builder: params named c1/c2/c3 (colour) become vec3, others floats */
  SF.glTool = def => SF.tool({
    id: def.id, name: def.name, cat: def.cat || 'Shader effects', p: def.p, learn: def.learn, kind: 'gl', presets: def.presets,
    r(p) {
      const u = {}; def.p.forEach(q => { u['u_' + q.k] = q.t === 'c' ? hex3(p[q.k]) : +p[q.k]; });
      const spec = { u, body: def.body }; const code = standalone(spec);
      return { gl: spec, anim: def.anim !== false, code, js: code, bg: '#000' };
    }
  });
})();
