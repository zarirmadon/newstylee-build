(function () {
  const U = SF.u;
  SF.tools = []; SF.cats = [];
  /* parameter builders */
  SF.R = (k, l, min, max, v, u = '', step = 1, adv) => ({ k, l, min, max, v, u, step, adv });
  SF.C = (k, l, v, adv) => ({ k, l, t: 'c', v, adv });
  SF.S = (k, l, o, v, adv) => ({ k, l, t: 's', o, v: v === undefined ? o[0] : v, adv });
  SF.B = (k, l, v, adv) => ({ k, l, t: 'b', v: v ? 1 : 0, adv });
  SF.X = (k, l, v, adv, rows) => ({ k, l, t: 'x', v, adv, rows });
  SF.catInfo = {};
  SF.category = (name, blurb) => { if (!SF.cats.includes(name)) SF.cats.push(name); SF.catInfo[name] = blurb || ''; };
  SF.tool = def => { def.id = def.id || def.name.toLowerCase().replace(/[^a-z0-9]+/g, '-'); SF.tools.push(def); return def; };
  SF.get = id => SF.tools.find(t => t.id === id);
  SF.defaults = t => { const v = {}; t.p.forEach(p => v[p.k] = p.v); return v; };

  /* ---------- scene / sample image for filter-type tools ---------- */
  SF.userImg = null;
  SF.scene = () => SF.userImg ? `url(${SF.userImg}) center/cover no-repeat` :
    'radial-gradient(circle at 72% 26%,#ffe08a 0 8%,#ffb15c 9% 12%,transparent 13%),radial-gradient(ellipse at 20% 100%,#1f4d3a 0 38%,transparent 39%),radial-gradient(ellipse at 70% 105%,#2a6a4a 0 45%,transparent 46%),linear-gradient(180deg,#2b6cb0 0,#7ec8f0 48%,#f6d7a8 70%,#2a6a4a 71%)';

  /* ---------- demo element builders ---------- */
  const FILL = d => `<div class="fill" style="${d}"></div>`;
  const CARD = d => `<div style="width:220px;height:140px;border-radius:16px;${d}"></div>`;
  const BTN = d => `<button style="border:0;padding:14px 30px;font:600 18px system-ui;${d}">Button</button>`;
  const TXT = (d, t = 'Hello') => `<div style="font:800 76px/1 system-ui;letter-spacing:-1px;text-align:center;${d}">${t}</div>`;
  SF.demo = { FILL, CARD, BTN, TXT };

  /* ---------- plain CSS tools ---------- */
  SF.cssTool = def => SF.tool({
    id: def.id, name: def.name, cat: def.cat, p: def.p, learn: def.learn, kind: 'css', presets: def.presets,
    r(p) {
      const d = def.css(p);
      const html = (def.el || CARD)(d.replace(/"/g, "'"), p);
      return { css: d, code: def.code ? def.code(p, d) : d, html: (def.style ? `<style>${def.style(p)}</style>` : '') + html, bg: typeof def.bg === 'function' ? def.bg(p) : (def.bg || '#0f1320') };
    }
  });

  /* ---------- SVG filter-effect tools ---------- */
  SF.fxTool = def => SF.tool({
    id: def.id, name: def.name, cat: def.cat || 'SVG effects', p: def.p, learn: def.learn, kind: 'fx', usesImage: true, presets: def.presets,
    r(p) {
      const box = def.box || 'x="-10%" y="-10%" width="120%" height="120%"';
      const f = `<filter id="__FX__" ${box} color-interpolation-filters="sRGB">${def.f(p)}</filter>`;
      const base = def.base ? def.base(p) : SF.scene();
      return {
        html: `<svg width="0" height="0" style="position:absolute"><defs>${f}</defs></svg><div class="fill" style="background:${base};filter:url(#__FX__)"></div>`,
        code: `<svg width="0" height="0" style="position:absolute"><defs>${f}</defs></svg>\n\n/* then, on any element: */\nfilter: url(#__FX__);`,
        css: 'filter: url(#__FX__);', fxsvg: `<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0"><defs>${f}</defs></svg>`, bg: '#0f1320'
      };
    }
  });
  /* give every filter its own id */
  SF.fxid = (s, id) => s.replace(/__FX__/g, id);

  /* method shorthand (draw(ctx){}) is not a valid function expression on its own */
  const fnSrc = f => { const s = f.toString(); return /^\s*(async\s+)?(function|\(|[A-Za-z_$][\w$]*\s*=>)/.test(s) && !/^\s*draw\s*\(/.test(s) ? s : 'function ' + s; };
  /* ---------- canvas tools ---------- */
  SF.cvTool = def => SF.tool({
    id: def.id, name: def.name, cat: def.cat, p: def.p, learn: def.learn, kind: 'canvas', presets: def.presets,
    r(p) {
      const draw = def.draw;
      const src = `/* ${def.name} — generated by StyleForge */\nconst rng = ${U.rng.toString()};\nconst draw = ${fnSrc(draw)};\nconst p = ${JSON.stringify(p)};\nconst c = document.querySelector('canvas'), ctx = c.getContext('2d');\ndraw(ctx, c.width, c.height, p, 0);`;
      return { draw: (ctx, w, h, t) => draw(ctx, w, h, p, t || 0), anim: !!def.anim, code: src, js: src, bg: def.bg || '#0f1320' };
    }
  });
})();
